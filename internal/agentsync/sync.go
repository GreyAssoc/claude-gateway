// watchLoop processes fsnotify events with debouncing.
func (s *Syncer) watchLoop() {
	// Debounce timer: wait 500ms after last event before syncing.
	const debounce = 500 * time.Millisecond
	timer := time.NewTimer(debounce)
	timer.Stop()

	var pendingPaths []string

	for {
		select {
		case <-s.done:
			return
		case event, ok := <-s.watcher.Events:
			if !ok {
				return
			}
			if !strings.HasSuffix(event.Name, ".md") {
				continue
			}
			if event.Op&(fsnotify.Create|fsnotify.Write) == 0 {
				continue
			}

			// If a new directory was created under claude agents, watch it.
			if event.Op&fsnotify.Create != 0 {
				if info, err := os.Stat(event.Name); err == nil && info.IsDir() {
					s.watcher.Add(event.Name)
					continue
				}
			}

			pendingPaths = append(pendingPaths, event.Name)
			timer.Reset(debounce)

		case <-timer.C:
			for _, path := range pendingPaths {
				s.handleFileChange(path)
			}
			pendingPaths = pendingPaths[:0]

		case err, ok := <-s.watcher.Errors:
			if !ok {
				return
			}
			log.Printf("agentsync: watcher error: %v", err)
		}
	}
}

func (s *Syncer) handleFileChange(path string) {
	content, err := os.ReadFile(path)
	if err != nil {
		return
	}
	text := string(content)

	// Don't re-sync files we generated.
	if hasSyncMarker(text) {
		return
	}

	// Debounce: skip if we synced this file very recently.
	s.mu.Lock()
	if last, ok := s.pending[path]; ok && time.Since(last) < time.Second {
		s.mu.Unlock()
		return
	}
	s.pending[path] = time.Now()
	s.mu.Unlock()

	// Determine direction based on which directory the file is in.
	switch {
	case strings.HasPrefix(path, s.claudeAgentDir):
		name := claudeAgentToOpenCodeName(path, s.claudeAgentDir)
		dest := filepath.Join(s.opencodeAgentDir, name)
		translated := claudeAgentToOpenCode(text, name)
		if err := os.WriteFile(dest, []byte(translated), 0o644); err == nil {
			log.Printf("agentsync: live sync claude→opencode agent %s", name)
		}

	case strings.HasPrefix(path, s.opencodeAgentDir):
		relPath := opencodeAgentToClaudePath(filepath.Base(path))
		dest := filepath.Join(s.claudeAgentDir, relPath)
		os.MkdirAll(filepath.Dir(dest), 0o755)
		translated := opencodeAgentToClaude(text)
		if err := os.WriteFile(dest, []byte(translated), 0o644); err == nil {
			log.Printf("agentsync: live sync opencode→claude agent %s", relPath)
		}

	case strings.HasPrefix(path, s.claudeCmdDir):
		dest := filepath.Join(s.opencodeCmdDir, filepath.Base(path))
		translated := claudeCmdToOpenCode(text)
		if err := os.WriteFile(dest, []byte(translated), 0o644); err == nil {
			log.Printf("agentsync: live sync claude→opencode cmd %s", filepath.Base(path))
		}

	case strings.HasPrefix(path, s.opencodeCmdDir):
		dest := filepath.Join(s.claudeCmdDir, filepath.Base(path))
		translated := opencodeCmdToClaude(text)
		if err := os.WriteFile(dest, []byte(translated), 0o644); err == nil {
			log.Printf("agentsync: live sync opencode→claude cmd %s", filepath.Base(path))
		}
	}
}

// allWatchDirs returns all directories to watch (including subdirectories).
func (s *Syncer) allWatchDirs() []string {
	dirs := []string{s.opencodeAgentDir, s.opencodeCmdDir, s.claudeCmdDir}

	// Walk Claude agent dir to find all subdirectories.
	filepath.Walk(s.claudeAgentDir, func(path string, info os.FileInfo, err error) error {
		if err == nil && info.IsDir() {
			dirs = append(dirs, path)
		}
		return nil
	})

	return dirs
}

// shouldOverwrite returns true if destPath doesn't exist or is older than srcModTime.
func shouldOverwrite(destPath string, srcModTime time.Time) bool {
	info, err := os.Stat(destPath)
	if err != nil {
		return true // doesn't exist
	}
	return srcModTime.After(info.ModTime())
}

func hasSyncMarker(content string) bool {
	return strings.Contains(content, syncMarker)
}
