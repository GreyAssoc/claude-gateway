// Package agentsync provides bidirectional syncing of agent and command files
// between Claude Code and OpenCode framework directories.
//
// Claude Code format: plain markdown, nested directories, bash code blocks.
// OpenCode format: YAML frontmatter + markdown, flat directories, !-prefixed commands.
//
// On startup, a full sync runs (newer file wins). Then fsnotify watches both
// directories for changes and translates on the fly. A sync marker in the
// translated file prevents infinite loops.
package agentsync

import (
	"log"
	"os"
	"path/filepath"
	"strings"
	"sync"
	"time"

	"github.com/fsnotify/fsnotify"
)

// syncMarker is embedded as an HTML comment in translated files.
// When we see this marker, we know the file was generated by us and
// should not trigger a reverse sync.
const syncMarker = "<!-- agentsync:generated -->"

// Syncer watches Claude Code and OpenCode agent/command directories and keeps
// them in sync bidirectionally.
type Syncer struct {
	claudeAgentDir  string // e.g. /workspace/.claude/agents
	claudeCmdDir    string // e.g. /workspace/.claude/commands
	opencodeAgentDir string // e.g. /workspace/.opencode/agents
	opencodeCmdDir   string // e.g. /workspace/.opencode/commands

	watcher  *fsnotify.Watcher
	done     chan struct{}
	stopOnce sync.Once

	// debounce prevents rapid re-syncs of the same file.
	mu       sync.Mutex
	pending  map[string]time.Time
}

// Config holds directory paths for the syncer.
type Config struct {
	ClaudeAgentDir   string
	ClaudeCmdDir     string
	OpencodeAgentDir string
	OpencodeCmdDir   string
}

// New creates a new Syncer.
func New(cfg Config) *Syncer {
	return &Syncer{
		claudeAgentDir:   cfg.ClaudeAgentDir,
		claudeCmdDir:     cfg.ClaudeCmdDir,
		opencodeAgentDir: cfg.OpencodeAgentDir,
		opencodeCmdDir:   cfg.OpencodeCmdDir,
		done:             make(chan struct{}),
		pending:          make(map[string]time.Time),
	}
}

// Start performs an initial full sync, then watches for changes.
func (s *Syncer) Start() error {
	// Ensure target directories exist.
	for _, dir := range []string{s.opencodeAgentDir, s.opencodeCmdDir, s.claudeAgentDir, s.claudeCmdDir} {
		if err := os.MkdirAll(dir, 0o755); err != nil {
			return err
		}
	}

	// Initial full sync.
	s.fullSync()

	// Start file watcher.
	w, err := fsnotify.NewWatcher()
	if err != nil {
		return err
	}
	s.watcher = w

	// Watch all relevant directories (including subdirectories for Claude agents).
	for _, dir := range s.allWatchDirs() {
		if err := w.Add(dir); err != nil {
			log.Printf("agentsync: cannot watch %s: %v", dir, err)
		}
	}

	go s.watchLoop()
	log.Printf("agentsync: watching for changes (claude=%s, opencode=%s)", s.claudeAgentDir, s.opencodeAgentDir)
	return nil
}

// Stop shuts down the watcher.
func (s *Syncer) Stop() {
	s.stopOnce.Do(func() {
		close(s.done)
		if s.watcher != nil {
			s.watcher.Close()
		}
	})
}

// fullSync syncs all agents and commands in both directions.
// For conflicts (same logical file in both), newer modification time wins.
func (s *Syncer) fullSync() {
	// Sync Claude agents → OpenCode.
	s.syncClaudeAgentsToOpenCode()
	// Sync OpenCode agents → Claude (only if Claude doesn't have a newer version).
	s.syncOpenCodeAgentsToClaude()
	// Sync commands both directions.
	s.syncClaudeCmdsToOpenCode()
	s.syncOpenCodeCmdsToClaude()
}

func (s *Syncer) syncClaudeAgentsToOpenCode() {
	err := filepath.Walk(s.claudeAgentDir, func(path string, info os.FileInfo, err error) error {
		if err != nil || info.IsDir() || !strings.HasSuffix(path, ".md") {
			return nil
		}
		content, err := os.ReadFile(path)
		if err != nil {
			return nil
		}
		if hasSyncMarker(string(content)) {
			return nil // generated file, skip
		}

		ocName := claudeAgentToOpenCodeName(path, s.claudeAgentDir)
		ocPath := filepath.Join(s.opencodeAgentDir, ocName)

		if shouldOverwrite(ocPath, info.ModTime()) {
			translated := claudeAgentToOpenCode(string(content), ocName)
			if err := os.WriteFile(ocPath, []byte(translated), 0o644); err != nil {
				log.Printf("agentsync: write %s: %v", ocPath, err)
			} else {
				log.Printf("agentsync: synced claude→opencode agent %s", ocName)
			}
		}
		return nil
	})
	if err != nil {
		log.Printf("agentsync: walk claude agents: %v", err)
	}
}

func (s *Syncer) syncOpenCodeAgentsToClaude() {
	entries, err := os.ReadDir(s.opencodeAgentDir)
	if err != nil {
		log.Printf("agentsync: read opencode agents: %v", err)
		return
	}
	for _, e := range entries {
		if e.IsDir() || !strings.HasSuffix(e.Name(), ".md") {
			continue
		}
		content, err := os.ReadFile(filepath.Join(s.opencodeAgentDir, e.Name()))
		if err != nil {
			continue
		}
		if hasSyncMarker(string(content)) {
			continue
		}

		claudeRelPath := opencodeAgentToClaudePath(e.Name())
		claudeFullPath := filepath.Join(s.claudeAgentDir, claudeRelPath)

		info, _ := e.Info()
		if info == nil {
			continue
		}
		if shouldOverwrite(claudeFullPath, info.ModTime()) {
			translated := opencodeAgentToClaude(string(content))
			dir := filepath.Dir(claudeFullPath)
			os.MkdirAll(dir, 0o755)
			if err := os.WriteFile(claudeFullPath, []byte(translated), 0o644); err != nil {
				log.Printf("agentsync: write %s: %v", claudeFullPath, err)
			} else {
				log.Printf("agentsync: synced opencode→claude agent %s", claudeRelPath)
			}
		}
	}
}

